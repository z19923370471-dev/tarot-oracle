/* 计算某张小阿卡纳的星象对应 { signKey, signName, planet, elementKey } */
function minorAstro(suitKey, rankNum) {
  const elementKey = SUITS.find(s => s.key === suitKey).element;
  let signKey, planet;
  if (rankNum >= 2 && rankNum <= 10) {
    const rec = PIP_DECANS[suitKey][rankNum];
    signKey = rec[0]; planet = PLANET_CN[rec[1]] || rec[1];
  } else if (rankNum === 1) {
    signKey = ACE_SIGN[suitKey];
    planet = SIGN_BY_KEY[signKey].ruler.split("/")[0].trim();
  } else {
    signKey = COURT_SIGN[suitKey][rankNum];
    planet = SIGN_BY_KEY[signKey].ruler.split("/")[0].trim();
  }
  const zs = SIGN_BY_KEY[signKey];
  return { signKey, signName: zs.sign, planet, elementKey };
}

